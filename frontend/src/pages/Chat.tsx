import { useEffect, useRef, useState } from 'react'
import { useQueryClient } from '@tanstack/react-query'
import { del, post } from '../api/client'
import { useChatHistory, useDashboard } from '../api/hooks'
import type { AskResponse, AssistantMessage } from '../api/types'
import { Icon } from '../ui/Icon'
import { PageFrame, useApp, usePages, useToast } from '../ui/shell'

const SUGGESTIONS = ['Can I eat papaya?', 'Is drumstick leaves good?', 'Foods with iron', 'What to eat this week?', 'Why do I feel nauseous?', 'Questions for my doctor', 'What does AFI mean?']

// Assistant replies are generated by our own server from curated content; only these tags are rendered.
const sanitize = (html: string) => html.replace(/<(?!\/?(b|br|ul|li|span)( class="disc")?\s*\/?>)[^>]*>/gi, '')

export function ChatPage() {
  const { user } = useApp()
  const { open } = usePages()
  const toast = useToast()
  const qc = useQueryClient()
  const hist = useChatHistory()
  const dash = useDashboard()
  const [msgs, setMsgs] = useState<AssistantMessage[]>([])
  const [typing, setTyping] = useState(false)
  const [text, setText] = useState('')
  const box = useRef<HTMLDivElement>(null)

  useEffect(() => { if (hist.data) setMsgs(hist.data.slice(-20)) }, [hist.data])
  useEffect(() => { box.current?.scrollTo({ top: box.current.scrollHeight, behavior: 'smooth' }) }, [msgs, typing])

  const send = async (q?: string) => {
    const body = (q ?? text).trim()
    if (!body || typing) return
    setText('')
    const temp: AssistantMessage = { id: 'tmp', role: 'user', content: body, isEmergency: false, createdAt: new Date().toISOString() }
    setMsgs(m => [...m, temp]); setTyping(true)
    try {
      const r = await post<AskResponse>('/assistant/messages', { text: body })
      await new Promise(res => setTimeout(res, 500))
      setMsgs(m => [...m.filter(x => x.id !== 'tmp'), r.question, r.answer])
      qc.setQueryData(['chat'], (old: AssistantMessage[] | undefined) => [...(old ?? []), r.question, r.answer])
    } catch (e) {
      setMsgs(m => m.filter(x => x.id !== 'tmp')); setText(body); toast((e as Error).message)
    } finally { setTyping(false) }
  }

  const clear = async () => { await del('/assistant/messages'); qc.setQueryData(['chat'], []); setMsgs([]); toast('Conversation deleted') }

  return (
    <PageFrame title="Ask Amma" chat right={<button className="icon-btn" onClick={clear} aria-label="Delete conversation"><Icon name="x" size={18} /></button>}>
      <div className="msgs" ref={box} aria-live="polite">
        <div className="msg bot">Hi {user.name} 👋 I'm Amma, your pregnancy guide.{dash.data?.pregnancy && <> You're in <b>week {dash.data.pregnancy.gestation.weeks}</b>.</>} Ask me about food, symptoms, scan terms or what to ask your doctor.
          <span className="disc">Educational only — I don't diagnose or prescribe. In an emergency, call 108 or your doctor.</span></div>
        {msgs.map(m => m.role === 'user'
          ? <div key={m.id + m.createdAt} className="msg me">{m.content}</div>
          : <div key={m.id} className={`msg bot ${m.isEmergency ? 'emer' : ''}`}>
              <span dangerouslySetInnerHTML={{ __html: sanitize(m.content) }} />
              {m.isEmergency && <div style={{ display: 'flex', gap: 8, marginTop: 10, flexWrap: 'wrap' }}>
                <a className="btn sm danger" href="tel:108" style={{ textDecoration: 'none' }}><Icon name="phone" size={15} /> Call 108</a>
                <button className="btn sm soft" onClick={() => open('emergency')}>Warning signs</button>
              </div>}
            </div>)}
        {typing && <div className="msg bot typing"><i /><i /><i /></div>}
      </div>
      <div className="sugg">{SUGGESTIONS.map(s => <button key={s} onClick={() => send(s)}>{s}</button>)}</div>
      <p className="ai-disc">Amma can make mistakes. Always confirm with your doctor.</p>
      <div className="chatbar">
        <button className="mic" onClick={() => toast('🎙️ Voice (Tamil/English) is coming soon')} aria-label="Voice input"><Icon name="mic" size={20} /></button>
        <input placeholder="Type your question…" value={text} onChange={e => setText(e.target.value)} onKeyDown={e => e.key === 'Enter' && send()} aria-label="Your question" maxLength={1000} />
        <button className="send" onClick={() => send()} aria-label="Send"><Icon name="send" size={19} /></button>
      </div>
    </PageFrame>
  )
}
